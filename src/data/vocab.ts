// SSC English vocabulary bank: idioms, one-word substitutions, synonyms, antonyms and
// commonly misspelt words that recur across CGL / CHSL / CPO papers.
// Meanings are written in our own words. Kept outside content/ so the content
// validator does not see it.

export type VocabListId = 'idioms' | 'ows' | 'synonyms' | 'antonyms' | 'spelling';

export interface VocabItem {
  /** Idiom / word / headword / correct spelling */
  term: string;
  /** One-line meaning */
  meaning: string;
  /** Short example sentence (optional) */
  example?: string;
  /** Synonyms (synonyms list) or antonyms (antonyms list) */
  words?: string[];
  /** The usual wrong spelling (spelling list) */
  wrong?: string;
}

export interface VocabList {
  id: VocabListId;
  label: string;
  short: string;
  blurb: string;
  items: VocabItem[];
}

type Row = [string, string, string?];

const basic = (rows: Row[]): VocabItem[] =>
  rows.map(([term, meaning, example]) => (example ? { term, meaning, example } : { term, meaning }));

const withWords = (rows: [string, string, string][]): VocabItem[] =>
  rows.map(([term, words, meaning]) => ({ term, meaning, words: words.split(',').map((w) => w.trim()) }));

