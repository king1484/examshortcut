"""MS PowerPoint deep notes."""

MP_BASICS = """### What PowerPoint is
**PowerPoint** is the **presentation program** of Microsoft Office. Its output — a **presentation** — is a series of **slides** shown one after another on a screen or projector. Each slide holds a mix of text, pictures, charts, video and shapes. Exams test the vocabulary: presentation = the file, slide = one page of it, and the file extensions.

### Placeholders, layouts and slide anatomy
- **Placeholders** are the dashed guiding boxes on a slide layout: a **title placeholder** at the top, a **content placeholder** below it (which offers one-click buttons for table, chart, SmartArt, picture, video), plus header/footer boxes.
- A **layout** fixes where these boxes sit: Title Slide, Title and Content, Two Content, Blank and so on. Changing the layout rearranges the boxes without touching your text.
- **Placeholders guide; text boxes add extra text** anywhere (Insert, Text Box).
- **Slide Master** (View tab) is the top design page: what you put or format there repeats on every slide — logos, fonts, background.

### Theme, template and master — three different words
| Word | What it really is |
|---|---|
| **Theme** | only the look — colours, fonts, effects |
| **Template** | theme + slide layouts + sample content + masters, saved as a file |
| **Slide Master** | the hidden design page that drives every slide |

A theme is a paint job; a template is a ready-made house. Both appear under File, New.

### New slide vs new presentation — the classic trap
- **Ctrl+N** creates a new **presentation** (a whole new file).
- **Ctrl+M** creates a new **slide** inside the current presentation (or use the New Slide button on the Home tab).
- **Ctrl+D duplicates** the selected slide.
One letter apart, completely different jobs — this pair is asked again and again.

### The extension family
| Extension | Meaning |
|---|---|
| **.pptx** | default presentation, PowerPoint 2007+ (X = XML) |
| **.ppt** | PowerPoint 97-2003 |
| **.ppsx** | **PowerPoint Show** — opens already running as a slideshow |
| **.potx** | template |
| **.pptm / .ppsm** | macro-enabled versions |

The X = 2007+, m = macro, t = template rule is shared with Word and Excel. A .ppsx file opens as a running show, not in the editor — a favourite trick option.

### Quick revision
- Presentation = file; slide = one page; placeholder = dashed guide box; layout = box arrangement.
- Theme = look only; template = theme + layouts + content; master = drives every slide.
- **Ctrl+N new presentation, Ctrl+M new slide, Ctrl+D duplicate slide.**
- Default .pptx (2007+), .ppt old, .ppsx opens running, .potx template."""

MP_VIEWS = """### The views of PowerPoint
| View | Purpose |
|---|---|
| **Normal** | **default** editing view — one slide large, with slides/outline and notes panes |
| **Outline View** | the text skeleton — titles and body text as a list, no graphics |
| **Slide Sorter** | all slides as thumbnails — the best place to **reorder, copy or delete slides** |
| **Notes Page** | slide on top, speaker notes below — printed for the presenter |
| **Reading View** | the show in a small window, for a quick check |
| **Slide Show** | full-screen delivery, one slide at a time |

Normal is where you build; **Slide Sorter is where you arrange**; Slide Show is where you deliver. Views are switched from the View tab or the buttons at the bottom-right.

### Slide Master — change once, apply everywhere
The **Slide Master** (View tab) is the design source of the presentation. Put a logo, set the fonts, choose the background colours or insert a page-number box **on the master**, and every slide based on it updates together. Editing the master is the answer whenever a question says "the same logo should appear on all 40 slides" or "change the font of the whole show in one step". Handout Master and Notes Master similarly control printed handouts and notes pages.

### Transitions vs animations — the most repeated distinction
- A **transition** is the movement **between two slides** — how slide 4 leaves and slide 5 arrives (Fade, Push, Wipe, Morph).
- An **animation** is an effect **on an object inside one slide** — a picture flies in, text dims. Animations come in four types: **Entrance, Emphasis, Exit and Motion Path**.

Memory hook: **transition = TRansfer between slides; animation = object acting**. "Which effect plays when one slide changes to the next?" — the answer is always a transition.

### Handouts and notes
- **Speaker notes** are written in the notes pane (Normal) or Notes Page view; the audience never sees them on screen.
- **Handouts** are printed sheets carrying several **slide thumbnails per page** (1, 2, 3, 4, 6 or 9 slides; the 3-slides layout adds lines for audience notes). Print them from File, Print by choosing Handouts.
- **Rehearse Timings** records how long each slide stays, useful for self-running shows.

### Quick revision
- Normal = default build view; Slide Sorter = thumbnail reordering; Notes Page = slide plus speaker notes.
- Slide Master changes every slide at once (logo, font, background).
- **Transition = between slides; Animation = on objects** (Entrance/Emphasis/Exit/Motion Path).
- Handout = printed page with several slide thumbnails; notes are never shown to the audience."""

MP_SHORTCUTS = """### Starting and stopping the show
| Key | Job |
|---|---|
| **F5** | run the show **from slide 1** |
| **Shift+F5** | run the show **from the current slide** |
| **Esc** | **end** the show |

The exam trap pair: **F5 starts, Esc stops** — never the reverse. Shift+F5 saves you from clicking through slide 1 every rehearsal.

### Moving inside a running show
| Key | Job |
|---|---|
| **N, Enter, Space, Page Down, Right/Down arrow** | **next** slide or effect |
| **P, Backspace, Page Up, Left/Up arrow** | **previous** slide |
| **number + Enter** | jump to that slide number |
| **B** | **black** screen (spotlight pause) |
| **W** | **white** screen |

N = next, P = previous. **B blacks and W whites the screen** — used when the speaker wants the audience to look at him, not the slide. B is NOT "back"; P is the back key. These during-show keys are a very common one-mark question.

### Editing and building shortcuts
- **Ctrl+M** new slide, **Ctrl+D** duplicate slide, **Ctrl+N** new presentation, **Ctrl+K** insert hyperlink.
- The copy-move family is shared with every Office program: **Ctrl+C** copy, **Ctrl+X** cut, **Ctrl+V** paste, **Ctrl+Z** undo, **Ctrl+S** save.
- Duplicate (Ctrl+D) places an exact copy on top of the original — handy for matching shapes; Copy-paste instead lets you choose where the copy lands.

### Delivery aids the exams name
- **Presenter View** — during the show, the presenter's screen shows the **current slide, next slide, speaker notes and a timer**, while the projector shows only the slide. The audience never sees the notes.
- **Rehearse Timings** — records the time spent per slide for self-running kiosks.
- **Ctrl+L** turns the mouse pointer into a **laser pointer** during the show (Microsoft 365 builds).
- **F1** during a show lists all the show controls.

### How the exam frames these questions
Shortcut questions here rarely go beyond a fixed pool: **start keys** (F5, Shift+F5, Esc), **traffic keys** (N, P, B, W, number+Enter), **build keys** (Ctrl+M, Ctrl+N, Ctrl+D, Ctrl+K) and the two delivery aids (Presenter View, Rehearse Timings). The traps are always reversals — F5 shown as "stop", B shown as "back", Shift+F5 shown as "from slide 1". Read the direction of the key in the option, not the letter. A quick self-test: F starts (F5 first slide, Shift+F5 here), Esc exits, N next, P previous, B black, W white, M more slides, D duplicate, K linK.

### Quick revision
- **F5 from first slide, Shift+F5 from current slide, Esc ends the show.**
- Next: N/Enter/Space/Page Down; Previous: P/Backspace/Page Up.
- **B = black screen, W = white screen; number+Enter jumps to a slide.**
- Ctrl+M new slide, Ctrl+D duplicate, Ctrl+K hyperlink.
- Presenter View: notes and timer for the speaker, slide only for the audience."""
