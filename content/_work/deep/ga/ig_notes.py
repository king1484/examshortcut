NOTES["ig-climate-soils"] = """
### Why India has a monsoon climate
India has a **tropical monsoon type** of climate: the whole year turns around the seasonal reversal of winds. In summer, heated land draws in moist ocean winds - the **south-west (SW) monsoon** - which normally strikes the **Kerala coast around 1 June** ("burst of the monsoon") and covers the whole country by **mid-July**. It has two branches: the **Arabian Sea branch** (dumps very heavy rain on the Western Ghats windward side) and the **Bay of Bengal branch** (up the Ganga plain into the north-east). By **mid-September** the monsoon begins to withdraw from the north-west.

### Where the rain falls - and where it does not
The windward side of the Western Ghats (Mumbai, Konkan, Kerala) gets drenched; the leeward side (Pune, interior Karnataka, Marathwada) lies in the **rain shadow**. **Mawsynram** and **Cherrapunji (Sohra)** in the Meghalaya's Khasi hills record some of the highest rainfall on Earth. Rajasthan's west (Jaisalmer) stays driest. A long dry spell inside the season is called a **break** in the monsoon. The **El Nino** warming of the eastern Pacific is linked with weaker Indian monsoons.

### The retreating monsoon and local winds
In October the monsoon winds leave; hot, humid days of this month are called **October heat**. As the winds retreat south they pick up moisture from the Bay of Bengal and give **October-December rain to the Tamil Nadu (Coromandel) coast** - the **north-east (NE) monsoon**, Tamil Nadu's main rain.
Pre-monsoon and local winds asked in exams:
| Name | Region | Nature / use |
|---|---|---|
| **Loo** | North Indian plains | Hot dry summer wind |
| **Mango showers** | Kerala, Karnataka coast | Help mango ripen |
| **Blossom showers** | Karnataka | Help coffee flower |
| **Kalbaisakhi / Nor'westers** | West Bengal, Assam | Evening thunderstorms; help tea and jute; **Bordoichila** in Assam |
| **Western disturbances** | Punjab, Haryana, west UP, J&K | Winter rain from the Mediterranean area; vital for **rabi wheat** |

### Soils of India (ICAR recognises 8 groups)
| Soil | Where | Key facts |
|---|---|---|
| **Alluvial** | Northern plains, deltas | **Most widespread (about 40% of area)**; *khadar* = new & fertile, *bhangar* = old with kankar; rice, wheat, sugarcane |
| **Black (Regur)** | Deccan trap - Maharashtra, Gujarat, MP | From **basalt**; rich in lime, iron, magnesium, potash; poor in nitrogen, phosphorus, humus; holds moisture; "self-ploughing" cracks; **cotton** |
| **Red and yellow** | TN, Karnataka, Odisha, Chhattisgarh | Red colour from **iron oxide**; sandy, poor in humus |
| **Laterite** | Western Ghats, Kerala, Odisha hills, NE | Formed by **leaching** in heat + heavy rain; hardens like brick (Latin *later*); tea, coffee, cashew after manuring |
| **Arid** | West Rajasthan | Sandy, saline, calcium (kankar) layers |
| **Saline / alkaline** | Dry areas; over-irrigated Punjab-Haryana | *Reh, kallar, usar*; reclaimed with **gypsum** |
| **Peaty / marshy** | Kerala (*kari*), Sundarbans | High humus, black, heavy |
| **Forest / mountain** | Himalayan slopes | Rich humus, acidic |

### Soil erosion and its cure
Running water cuts **gully erosion**, which turns land into bare **ravines** (the Chambal badlands); even removal of the topsoil layer is **sheet erosion**; open land in dry areas suffers **wind erosion**. Remedies: **contour ploughing, terrace farming, strip cropping, shelter belts of trees, afforestation**.

### Quick revision
- SW monsoon hits Kerala about 1 June; two branches - Arabian Sea and Bay of Bengal; withdraws from NW by mid-September.
- Rain shadow on the leeward Ghats; Mawsynram wettest; Tamil Nadu's main rain from the retreating (NE) monsoon in Oct-Dec.
- Loo = summer north India; mango showers = Kerala; blossom = coffee; Kalbaisakhi = Bengal-Assam tea.
- Black soil: basalt, cotton, rich in LIMP, poor in N-P-humus. Laterite: leaching, brick-hard. Saline soil treated with gypsum.
- Alluvial is the most widespread soil; gully erosion makes Chambal ravines.
"""

