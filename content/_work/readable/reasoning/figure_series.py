# ------------------------------------------------------------------ frame model
POS = {0: (0, 0), 1: (0, 1), 2: (0, 2), 3: (1, 2), 4: (2, 2), 5: (2, 1), 6: (2, 0), 7: (1, 0)}
ARR = "↑↗→↘↓↙←↖"     # index * 45 degrees clockwise from up
QN = ["TL", "TR", "BR", "BL"]  # quarters, clockwise


def border(marks, extra=None):
    """marks: dict pos -> char. Returns 3 lines (+ optional extra line)."""
    g = [[" "] * 3 for _ in range(3)]
    for p, (r, c) in POS.items():
        g[r][c] = "."
    for p, ch in marks.items():
        r, c = POS[p]
        g[r][c] = ch
    lines = [" ".join(r) for r in g]
    if extra is not None:
        lines.append(extra)
    return lines


def quarters(shaded, arrow=None):
    g = [["." , "."], [".", "."]]
    cell = {0: (0, 0), 1: (0, 1), 2: (1, 1), 3: (1, 0)}
    for q in shaded:
        r, c = cell[q]
        g[r][c] = "#"
    lines = ["".join(r) for r in g]
    if arrow is not None:
        lines = [ARR[arrow % 8] + " " + lines[0], "  " + lines[1]]
    return lines


def pad(lines, h, w):
    return [l.ljust(w) for l in lines] + [" " * w] * (h - len(lines))


def side(frames, sep="   ", labels=None):
    h = max(len(f) for f in frames)
    ws = [max(len(l) for l in f) for f in frames]
    if labels:
        ws = [max(w, len(lb)) for w, lb in zip(ws, labels)]
    cols = [pad(f, h, w) for f, w in zip(frames, ws)]
    out = []
    if labels:
        out.append(sep.join(lb.ljust(w) for lb, w in zip(labels, ws)).rstrip())
    for i in range(h):
        out.append(sep.join(c[i] for c in cols).rstrip())
    return "\n".join(out)


def fence(s):
    return "```\n" + s + "\n```"


LET = "ABCD"


def mk(series, correct, wrongs, k, intro="Find the figure that comes next in the series."):
    """series: list of frames (line lists). Options are frames too; correct sits at index k."""
    opts = list(wrongs)
    opts.insert(k, correct)
    assert len({tuple(o) for o in opts}) == 4, "options must be distinct"
    assert opts[k] == correct and sum(o == correct for o in opts) == 1
    q = (intro + "\n\n**Series**\n" + fence(side(series, sep="  >  ")) + "\n\n**Options**\n"
         + fence(side(opts, sep="     ", labels=[f"({LET[i]})" for i in range(4)])))
    return q, f"({LET[k]})"


def walk(start, steps, mod=8):
    out = [start]
    for s in steps:
        out.append((out[-1] + s) % mod)
    return out


def ex(q_ans, steps):
    q, a = q_ans
    return {"q": q, "steps": steps, "answer": a}


